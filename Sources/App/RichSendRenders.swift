/// Rich mail sending renders (`rm-composer-{forward,attachments,inline-image,over-limit,large-warning,approve-attachments}`)
/// and the sending `RICHMAIL-BENCH` lines (`buildRich` with a 25 MB file, opening a forward of a 5-attachment mail). The Moonfield cast only: memory stores, a pinned clock, attachment bytes
/// generated in code under `<dir>/scratch`, no network, no Keychain, no user defaults.
@MainActor
enum RichSendRenders {
    @discardableResult
    static func run(dir: URL, now: Date, save: (AnyView, String, [String: Any]) -> Void) -> Int {
        let scratch = dir.appendingPathComponent("scratch", isDirectory: true)
        let store = FakeMailAttachments(folder: scratch.appendingPathComponent("send-attachments", isDirectory: true))
        var count = 0
        func composer(_ model: ComposerModel, _ name: String, _ state: String, mac: ColorScheme = .dark,
                      size: CGSize = CGSize(width: 640, height: 640)) {
            model.refreshEstimate()
            let view = ComposerView(model: model).frame(width: size.width, height: size.height)
                .environment(\.colorScheme, mac).environment(\.headlessRender, true)
            save(AnyView(view), "\(name).png", ["window": "rich-mail", "surface": "composer", "state": state,
                                                "mac": mac == .dark ? "dark" : "light", "height": Int(size.height),
                                                "format": model.format == .rich ? "rich" : "plain",
                                                "chips": model.attachments.count, "estimate": model.estimatedSize,
                                                "quote": model.quote == nil ? "none" : model.quoteExpanded ? "open" : "collapsed",
                                                "quoteCollapsed": model.quote != nil && !model.quoteExpanded,
                                                "approval": model.approval != nil])
            count += 1
        }

        for mac in [ColorScheme.light, .dark] {
            let look = mac == .dark ? "dark" : "light"
            composer(forward(now: now, store: store), "rm-composer-forward-\(look)", "forward", mac: mac)
            composer(withAttachments(now: now), "rm-composer-attachments-\(look)", "attachments", mac: mac)
            composer(overLimit(now: now), "rm-composer-over-limit-\(look)", "over-limit", mac: mac)
        }
        composer(inlineImage(now: now), "rm-composer-inline-image", "inline-image")
        composer(largeWarning(now: now), "rm-composer-large-warning", "large-warning")
        let approve = withAttachments(now: now, to: RichMailCast.juniper.display)
        settle { await approve.send() }
        composer(approve, "rm-composer-approve-attachments", "approve-attachments")
        print("  rich mail (sending): \(count) PNGs")
        bench(scratch: scratch, now: now)
        return count
    }

    /// Runs async main-actor work to completion while the main run loop turns (the render run is synchronous).
    static func settle(_ work: @escaping @MainActor () async -> Void) {
        final class Box { var done = false }
        let box = Box()
        Task { @MainActor in
            await work()
            box.done = true
        }
        let limit = Date().addingTimeInterval(20)
        while !box.done, Date() < limit { RunLoop.main.run(mode: .default, before: Date().addingTimeInterval(0.01)) }
    }

    // MARK: Models (cast only)

    static func model(_ request: ComposerRequest, now: Date, store: MailAttachmentStore? = nil) -> ComposerModel {
        let actions = FakeMailActions(store: FakeMailStore())
        let prefs = RichComposerFixtures.prefs()
        let files = store ?? EmptyStores.shared
        return ComposerModel(request: request, accounts: RichComposerFixtures.directory().accounts, safeSend: true,
                             actions: { actions }, prefs: { prefs }, local: MemoryMailLocalStore(), clock: { now }, schedule: { _, _ in },
                             toasts: MailToastCenter(clock: { now }, schedule: { _, _ in }), attachmentStore: { files })
    }

    /// Generated bytes standing in for a file of `bytes` (no binary assets).
    static func file(_ m: ComposerModel, _ name: String, _ bytes: Int) {
        m.attach(imageData: FakeMailAttachments.filler(bytes), name: name, asFile: true)
    }

    static func photo(_ w: Int, _ h: Int, color: UInt32) -> Data {
        FakeMailAttachments.image(.init(threadR: "render", messageId: "render", partId: "1", mimeType: "image/jpeg", bytes: 0,
                                        pixels: (w, h), color: color), type: .jpeg) ?? Data()
    }

    /// Forwarding Priya Starling's plan to Ines Marlowe: three files re-attached (downloaded), the original under the editor.
    static func forward(now: Date, store: MailAttachmentStore) -> ComposerModel {
        let m = model(RichComposerFixtures.priyaForward(now: now), now: now, store: store)
        m.to = RichMailCast.ines.display
        m.body = "Ines, here is Priya\u{2019}s plan with the budget and the menu for the tasting.\n" + m.body
        settle { await m.loadForwardedAttachments() }
        return m
    }

    /// A new message from Orbital Pickle Co. with four files: a PDF, a spreadsheet, a photo and an invite.
    static func withAttachments(now: Date, to: String? = nil) -> ComposerModel {
        let m = model(.new(from: RichMailCast.orb.id), now: now)
        m.to = to ?? (RichMailCast.priya.display + ", " + RichMailCast.milo.display)
        m.subject = "Label proofs and the Q4 budget"
        m.body = "Hi both,\n\nThe label proofs and the budget are attached, with a photo of the jars from Caf\u{00E9} Nowhere.\n" + m.body
        file(m, "Label proofs.pdf", 2_400_000)
        file(m, "Budget Q4.xlsx", 186_000)
        m.attach(imageData: photo(1200, 800, color: 0x9CC5A1), name: "Jars at Caf\u{00E9} Nowhere.jpg", asFile: true)
        file(m, "Rehearsal.ics", 2_100)
        return m
    }

    /// A photo pasted into the body (inline, sent as a cid part).
    static func inlineImage(now: Date) -> ComposerModel {
        let m = model(.new(from: RichMailCast.fam.id), now: now)
        m.to = RichMailCast.mom.display
        m.subject = "The dock this morning"
        m.body = "Mom, the dock this morning:\n\nSee you at the lake house on Saturday.\n" + m.body
        let at = NSMaxRange((m.document.string as NSString).range(of: "morning:\n"))
        m.editorSelected(NSRange(location: at, length: 0), typing: [:])
        m.attach(imageData: photo(1200, 560, color: 0x7FA7D9), name: "Dock.jpg")
        return m
    }

    /// 19.6 MB of files: over Gmail's 25 MB once encoded.
    static func overLimit(now: Date) -> ComposerModel {
        let m = model(.new(from: RichMailCast.cmt.id), now: now)
        m.to = RichMailCast.kofi.display
        m.subject = "Tour footage"
        m.body = "Kofi, the footage from the Caf\u{00E9} Nowhere set.\n" + m.body
        file(m, "Set one.mov", 12_400_000)
        file(m, "Set two.mov", 7_200_000)
        return m
    }

    /// About 11 MB once encoded: the quiet warning.
    static func largeWarning(now: Date) -> ComposerModel {
        let m = model(.new(from: RichMailCast.cmt.id), now: now)
        m.to = RichMailCast.theo.display
        m.subject = "Moodboard for the tour poster"
        m.body = "Theo, the moodboard for the poster.\n" + m.body
        file(m, "Moodboard.zip", 8_100_000)
        return m
    }

    // MARK: RICHMAIL-BENCH (the optimised -O dev build that --render runs)

    static func maxRSS() -> Int {
        var usage = rusage()
        getrusage(RUSAGE_SELF, &usage)
        return Int(usage.ru_maxrss)   // bytes on macOS
    }

    static func bench(scratch: URL, now: Date) {
        let fm = FileManager.default
        try? fm.createDirectory(at: scratch, withIntermediateDirectories: true)
        // buildRich with a 25 MB attachment, straight to a file.
        let source = scratch.appendingPathComponent("bench-25mb.bin"), out = scratch.appendingPathComponent("bench-25mb.eml")
        var chunk = Data(count: 1 << 20)
        chunk.withUnsafeMutableBytes { raw in
            guard let p = raw.bindMemory(to: UInt8.self).baseAddress else { return }
            var x: UInt32 = 2_463_534_242
            for i in 0..<(1 << 20) { x ^= x << 13; x ^= x >> 17; x ^= x << 5; p[i] = UInt8(truncatingIfNeeded: x) }
        }
        if fm.createFile(atPath: source.path, contents: nil), let handle = try? FileHandle(forWritingTo: source) {
            for _ in 0..<25 { try? handle.write(contentsOf: chunk) }
            try? handle.close()
        }
        let mail = RichOutgoingMail(headers: OutgoingMail(from: MailAddress(name: RichMailCast.owner, email: RichMailCast.orb.email),
                                                          to: [MailAddress(name: RichMailCast.priya.name, email: RichMailCast.priya.email)],
                                                          subject: "Moodboard", body: "", messageID: MIMEBuilder.newMessageID(), date: now),
                                    text: "The moodboard, all 25 MB of it.", html: "<div>The moodboard, all 25 MB of it.</div>",
                                    files: [MIMEAttachment(filename: "Moodboard.zip", mimeType: "application/zip", contentId: nil, source: .file(source))])
        let before = maxRSS()
        let t0 = Date()
        let bytes = (try? MIMEBuilder.buildRich(mail, to: out)) ?? 0
        let seconds = Date().timeIntervalSince(t0)
        let extra = max(0, maxRSS() - before)
        let mb = Double(extra) / 1_048_576
        print(String(format: "RICHMAIL-BENCH buildRich 25MB to file %.2f s (budget 1.5 s) peak-extra=%.0f MB (budget 80) bytes=%d %@",
                     seconds, mb, bytes, seconds <= 1.5 && mb <= 80 ? "pass" : "OVER"))
        try? fm.removeItem(at: source)
        try? fm.removeItem(at: out)

        // Opening a composer on a forward of a 5-attachment mail: the model and the first headless paint; the files
        // download afterwards (not timed).
        let five = RichMailThreads.attachmentList.filter { ["2", "3", "5", "6", "7"].contains($0.id) }
        let request = ComposerRequest.forward(RichMailThreads.attachments.thread(now: now),
                                              RichComposerFixtures.message(RichMailBodies.attachments, now: now, attachments: five))
        let t1 = Date()
        let m = model(request, now: now)
        let view = ComposerView(model: m).frame(width: 640, height: 640).environment(\.colorScheme, .dark).environment(\.headlessRender, true)
        let renderer = ImageRenderer(content: view)
        renderer.scale = 2
        _ = renderer.nsImage
        let paint = Date().timeIntervalSince(t1) * 1000
        print(String(format: "RICHMAIL-BENCH forward-open first-paint=%.0f ms (budget 200) chips=%d %@", paint, m.attachments.count,
                     paint <= 200 ? "pass" : "OVER"))
    }
}
#endif
